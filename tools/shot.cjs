const { chromium } = require('playwright');
(async () => {
  const out = process.argv[2];
  const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
  const logs = [];
  page.on('console', (m) => logs.push(m.type() + ': ' + m.text()));
  page.on('pageerror', (e) => logs.push('ERR ' + e.message));
  await page.goto('http://localhost:8765/index.html');
  await page.waitForFunction(() => window.__scene && window.__scene.player, null, { timeout: 15000 });
  await page.waitForTimeout(1200);
  const st = () => page.evaluate(() => { const p = window.__scene.player; return { x: Math.round(p.x), y: Math.round(p.body.bottom), vx: Math.round(p.body.velocity.x), vy: Math.round(p.body.velocity.y), g: p.body.blocked.down, hp: p.hp, renderer: window.__game.renderer.type }; });
  console.log('start', JSON.stringify(await st()));
  await page.screenshot({ path: out + '-0.png' });
  await page.keyboard.down('ArrowRight'); await page.waitForTimeout(700);
  console.log('run', JSON.stringify(await st()));
  await page.keyboard.down('z'); await page.waitForTimeout(250);
  console.log('jump', JSON.stringify(await st()));
  await page.screenshot({ path: out + '-1.png' });
  await page.keyboard.up('z'); await page.waitForTimeout(500);
  await page.keyboard.press('c'); await page.waitForTimeout(60);
  console.log('dash', JSON.stringify(await st()));
  await page.waitForTimeout(800);
  await page.keyboard.press('x'); await page.waitForTimeout(40);
  await page.screenshot({ path: out + '-2.png' });
  await page.waitForTimeout(1500);
  console.log('later', JSON.stringify(await st()));
  await page.keyboard.up('ArrowRight');
  await page.screenshot({ path: out + '-3.png' });
  console.log(logs.slice(0, 20).join('\n'));
  await browser.close();
})();
