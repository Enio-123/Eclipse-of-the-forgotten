// Percorre o fluxo: título -> escolha de arma -> abertura -> ponte, tirando capturas
const { chromium } = require('playwright');
const OUT = process.argv[2] || '/tmp/shots';
(async () => {
  const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--autoplay-policy=no-user-gesture-required'] });
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
  const errs = [];
  page.on('pageerror', (e) => errs.push('ERR ' + e.message + '\n' + (e.stack || '').split('\n').slice(0, 4).join('\n')));
  page.on('response', (r) => { if (r.status() >= 400) errs.push('HTTP ' + r.status() + ' ' + r.url()); });
  page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errs.push(m.type() + ' ' + m.text()); });
  await page.goto('http://localhost:8765/index.html');
  await page.waitForSelector('#screen-menu.show', { timeout: 20000 });
  await page.waitForTimeout(2500);
  await page.screenshot({ path: `${OUT}/01-title.png` });
  await page.click('[data-cmd="new"]');
  await page.waitForSelector('#screen-path.show');
  await page.click('#screen-path [data-cmd="confirm"]');
  await page.waitForSelector('#screen-weapons.show');
  await page.waitForTimeout(900);
  await page.screenshot({ path: `${OUT}/02-weapons.png` });
  await page.click('.card[data-w="sword"]');
  await page.waitForTimeout(500);
  await page.click('.card[data-w="scythe"]');
  await page.waitForTimeout(300);
  await page.click('#screen-weapons [data-cmd="confirm"]');
  await page.waitForTimeout(3300);
  await page.screenshot({ path: `${OUT}/03-story.png` });
  await page.keyboard.press('Space');
  await page.waitForFunction(() => window.__scene && window.__scene.player, null, { timeout: 15000 });
  await page.waitForTimeout(1500);
  await page.screenshot({ path: `${OUT}/04-pan.png` });
  await page.waitForTimeout(5200);
  await page.screenshot({ path: `${OUT}/05-wake.png` });
  await page.waitForTimeout(1500);
  const st = await page.evaluate(() => { const s = window.__scene; return { x: s.player.x, pose: s.player.pose, frozen: s.player.frozen, room: s.room.id }; });
  console.log(JSON.stringify(st));
  await page.keyboard.down('KeyD'); await page.waitForTimeout(1200); await page.keyboard.up('KeyD');
  await page.waitForTimeout(400);
  await page.screenshot({ path: `${OUT}/06-walk.png` });
  console.log(errs.join('\n') || 'sem erros');
  await browser.close();
})();
