const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
  page.on('pageerror', (e) => console.log('ERR ' + e.message));
  const URL = 'http://localhost:8765/index.html';
  await page.goto(URL);
  await page.evaluate(() => localStorage.clear());
  await page.goto(URL);
  await page.waitForSelector('#screen-menu.show', { timeout: 60000 });
  await page.evaluate(() => {
    const p = window.__progress;
    p.reset(); p.prologueDone = true; p.kintsugi = 1; p.starter = 'eclipse';
    window.__settings.data.weapon = 'eclipse'; window.__settings.save();
    p.abilities = new Set(['wall', 'double', 'hook', 'veil']);
    p.seen.add('memory:vale'); p.seen.add('gate:catacumbas');
    p.save();
    window.__ui.closeAll();
    const g = window.__game;
    g.scene.getScene('title').scene.stop();
    g.scene.start('game', { room: 'ponte', entry: 'P', from: 'continue' });
  });
  await page.waitForFunction(() => window.__scene && window.__scene.player && window.__scene.clock > 0.3, null, { timeout: 60000 });
  const st = () => page.evaluate(() => {
    const s = window.__scene; const p = s.player;
    return { clock: +s.clock.toFixed(2), x: Math.round(p.x), y: Math.round(p.body.bottom), pose: p.pose, frozen: p.frozen, cin: s.cinematic, ground: p.onGround, canAim: p.canAim, aiming: s.magic && s.magic.aiming, raw: window.__raw ? window.__raw.enabled : 'n/a', ui: window.__ui.open, held: JSON.stringify(s.controls.held), atk: p.attacking, w: p.weapon.id };
  });
  const waitGame = async (sec) => { const c0 = await page.evaluate(() => window.__scene.clock); await page.waitForFunction((c) => window.__scene.clock >= c, c0 + sec, { timeout: 60000, polling: 16 }); };
  await page.evaluate(() => { const s = window.__scene; const p = s.player; p.teleport(320, p.body.bottom); p.facing = 1; window.__c = s.spawn('c', p.x + 110, p.body.bottom); window.__c.facing = -1; });
  await waitGame(0.4);
  console.log('placed', JSON.stringify(await st()), JSON.stringify(await page.evaluate(() => ({ cx: window.__c.zone.x, hp: window.__c.hp, hurt: window.__scene.player.hurtT, inv: window.__scene.player.invuln }))));
  await page.keyboard.down('KeyJ');
  await waitGame(0.06);
  console.log('J down', JSON.stringify(await st()), await page.evaluate(() => window.__scene.arrows.length));
  await page.keyboard.up('KeyJ');
  await waitGame(0.08);
  console.log('J up', JSON.stringify(await st()), await page.evaluate(() => window.__scene.arrows.map((a) => a.orb + ':' + a.hostile + ':' + Math.round(a.x)).join(',')));
  await waitGame(0.6);
  console.log('later', await page.evaluate(() => ({ cx: window.__c.zone.x, hp: window.__c.hp })));
  await page.keyboard.down('KeyJ'); await page.waitForTimeout(150);
  console.log('J held', JSON.stringify(await st()));
  await page.keyboard.up('KeyJ');
  await page.waitForTimeout(300);
  console.log('after J', JSON.stringify(await st()), await page.evaluate(() => window.__scene.arrows.length));
  await page.keyboard.down('KeyI'); await page.waitForTimeout(150); await page.keyboard.up('KeyI');
  await page.waitForTimeout(300);
  console.log('after I', JSON.stringify(await st()));
  await browser.close();
})();
